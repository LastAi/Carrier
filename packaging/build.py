"""Build a standalone Carrier for the current OS.

    python packaging/build.py                    # secure edition (default)
    python packaging/build.py --variant network  # with the LAN server (future)

PyInstaller cannot cross-compile, so run this once on each OS you want to
ship for (Windows → .exe, macOS → .app, Linux → folder/AppImage-ready).
The CI workflow ``.github/workflows/build.yml`` does all three.

Output: ``dist/Carrier-<version>-<os>-<variant>/`` containing

* ``Carrier`` (``Carrier.exe`` / ``Carrier.app``) — the desktop app,
* ``carrier-cli`` — terminal tools and commands (also used by the Claude
  Code Stop hook in compiled builds),
* ``BUILD-INFO.txt`` — version, variant and the network-check result.

Claude Code itself is not bundled by default (it is ~280 MB and users
already have it); the app uses the ``claude`` command on PATH. Pass
``--bundle-claude`` to include the Agent SDK's copy — for your own use only:
Claude Code is not open source, has its own terms, and must not be included
in builds you publish.

Editions
--------
secure (default)
    The optional network package ``carrier_net`` is excluded at build time
    (``--exclude-module``) and the finished bundle is scanned to prove it
    is absent. The core package contains no networking code at all
    (enforced by tests/test_isolation.py).
network
    Includes ``carrier_net`` (the LAN server). Not part of this release yet —
    the command explains this and stops.

Note: pywebview, the window library, contains its own small HTTP server
module. Carrier never starts it (the page is loaded as an HTML string with
``http_server=False``), but the code is present in every edition because
pywebview imports it. This is recorded in BUILD-INFO.txt for transparency.
"""

from __future__ import annotations

import argparse
import platform
import shutil
import subprocess
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src"
NETWORK_PACKAGE = "carrier_net"


def os_tag() -> str:
    return {"win32": "windows", "darwin": "macos"}.get(sys.platform, "linux") + "-" + platform.machine().lower()


def version() -> str:
    sys.path.insert(0, str(SRC))
    from carrier import __version__

    return __version__


SPEC_TEMPLATE = '''\
# Generated by packaging/build.py — do not edit by hand.
import sys
from PyInstaller.utils.hooks import collect_all, collect_data_files, collect_submodules

datas, binaries, hidden = [], [], []
for pkg in ("webview", "claude_agent_sdk", "textual"):
    d, b, h = collect_all(pkg)
    datas += d; binaries += b; hidden += h
datas += collect_data_files("carrier")          # web page, criteria, TUI styles
hidden += collect_submodules("carrier")
excludes = {excludes!r}

# The Agent SDK ships its own ~280 MB copy of Claude Code. Users of Carrier
# already have Claude Code installed (and logged in), and the SDK falls back
# to the `claude` on PATH, so leave the copy out unless asked for.
if not {bundle_claude!r}:
    datas = [d for d in datas if "_bundled" not in d[0]]
    binaries = [b for b in binaries if "_bundled" not in b[0]]

def analysis(script):
    return Analysis([script], pathex=[{src!r}], datas=datas, binaries=binaries,
                    hiddenimports=hidden, excludes=excludes, noarchive=False)

app = analysis({entry_app!r})
cli = analysis({entry_cli!r})

app_exe = EXE(PYZ(app.pure), app.scripts, [], exclude_binaries=True, name="Carrier",
              console=False, icon={icon!r})
cli_exe = EXE(PYZ(cli.pure), cli.scripts, [], exclude_binaries=True, name="carrier-cli",
              console=True, icon={icon!r})

coll = COLLECT(app_exe, app.binaries, app.datas, cli_exe, cli.binaries, cli.datas,
               name={dist_name!r})

if sys.platform == "darwin":
    BUNDLE(coll, name="Carrier.app", bundle_identifier="dev.carrier.app", icon={icon!r})
'''


def build(variant: str, bundle_claude: bool = False) -> Path:
    import importlib.util

    if importlib.util.find_spec("PyInstaller") is None:
        sys.exit("PyInstaller is not installed:  pip install -e \".[build]\"")

    if variant == "network":
        if not (SRC / NETWORK_PACKAGE).exists():
            sys.exit("The network edition is not part of this release yet. "
                     "Build the secure edition (the default) instead.")
        excludes: list[str] = []
    else:
        excludes = [NETWORK_PACKAGE]
    # Never needed by Carrier; pulled in by optional code paths of dependencies.
    # (cryptography is only used by pywebview's TLS server, which we never start.)
    excludes += ["numpy", "PIL", "cryptography", "tkinter", "matplotlib", "IPython",
                 "pytest", "playwright", "pydoc_data"]

    dist_name = f"Carrier-{version()}-{os_tag()}-{variant}"
    work = ROOT / "build" / "pyinstaller"
    work.mkdir(parents=True, exist_ok=True)
    icon = ROOT / "packaging" / ("carrier.ico" if sys.platform == "win32" else "carrier.icns")
    spec = work / "carrier.spec"
    spec.write_text(SPEC_TEMPLATE.format(
        excludes=excludes, src=str(SRC),
        entry_app=str(ROOT / "packaging" / "entry_app.py"),
        entry_cli=str(ROOT / "packaging" / "entry_cli.py"),
        icon=str(icon) if icon.exists() else None, dist_name=dist_name, bundle_claude=bundle_claude,
    ), encoding="utf-8")

    out = ROOT / "dist"
    target = out / dist_name
    if target.exists():
        shutil.rmtree(target)
    subprocess.run([sys.executable, "-m", "PyInstaller", "--noconfirm", "--clean",
                    "--distpath", str(out), "--workpath", str(work / "work"), str(spec)],
                   check=True, cwd=ROOT)

    if sys.platform == "darwin":
        # PyInstaller writes the .app next to the folder; keep everything for
        # this edition together (and inside what verify() scans).
        app = out / "Carrier.app"
        if app.exists():
            dest = target / "Carrier.app"
            if dest.exists():
                shutil.rmtree(dest)
            shutil.move(str(app), str(dest))

    # The license travels with every build (AGPL: recipients get the terms).
    for name in ("LICENSE", "README.md"):
        if (ROOT / name).exists():
            shutil.copy2(ROOT / name, target / name)

    found = verify(target, variant)
    (target / "BUILD-INFO.txt").write_text(textwrap.dedent(f"""\
        Carrier {version()}
        Edition: {variant}
        Platform: {os_tag()}
        Python: {platform.python_version()}

        License: AGPL-3.0-only (see LICENSE). Source: the Carrier repository.
        {"Includes Claude Code (personal build: do not publish)." if bundle_claude else "Claude Code: not included (uses the installed claude)."}

        Network check: {"PASSED — no Carrier network code in this build" if variant == "secure"
                        else "network edition — includes " + NETWORK_PACKAGE}
        {"Files matching " + NETWORK_PACKAGE + ": none" if not found else "Found: " + ", ".join(found)}

        The desktop app opens no listening port: its page is loaded as an HTML
        string with pywebview's HTTP server disabled. pywebview's own (unused)
        server module is still present because pywebview imports it.
        """), encoding="utf-8")
    print(f"\nBuilt {target}")
    return target


def verify(target: Path, variant: str) -> list[str]:
    """Scan the bundle for the network package; fail the secure build if found."""
    found = [str(p.relative_to(target)) for p in target.rglob(f"*{NETWORK_PACKAGE}*")]
    if variant == "secure" and found:
        sys.exit(f"SECURE BUILD FAILED: network code found in the bundle: {found}")
    return found


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--variant", choices=["secure", "network"], default="secure")
    ap.add_argument("--bundle-claude", action="store_true",
                    help="include the Agent SDK's own copy of Claude Code (~280 MB) — personal "
                         "builds only, never for publishing; by default the installed `claude` is used")
    args = ap.parse_args()
    build(args.variant, args.bundle_claude)


if __name__ == "__main__":
    main()
